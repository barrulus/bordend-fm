Color hex(std::uint32_t rgb) { return Color::rgb(rgb); }

bool near(Color a, Color b) {
    constexpr float tolerance = 1.0F / 255.0F;
    return std::abs(a.r - b.r) <= tolerance && std::abs(a.g - b.g) <= tolerance &&
           std::abs(a.b - b.b) <= tolerance && std::abs(a.a - b.a) <= tolerance;
}

// The user's config folder with gtk-4.0 and gtk-3.0 inside, as a desktop leaves it.
struct GtkHome {
    TempDir dir;

    [[nodiscard]] std::vector<std::filesystem::path> paths() const {
        return {dir.path / "gtk-4.0" / "gtk.css", dir.path / "gtk-3.0" / "gtk.css"};
    }

    void write(const std::string& file, std::string_view text) const {
        std::filesystem::create_directories((dir.path / file).parent_path());
        dir.write(file, text);
    }
};

bool run_until(EventLoop& loop, const std::function<bool()>& done) {
    bool ok = false;
    const auto poll = loop.add_timer(1ms, 1ms, [&] {
        if (done()) {
            ok = true;
            loop.quit(0);
        }
    });
    const auto watchdog = loop.add_timer(5s, 0ms, [&loop] { loop.quit(1); });
    loop.run();
    loop.remove(poll);
    loop.remove(watchdog);
    return ok;
}

